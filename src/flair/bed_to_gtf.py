#!/usr/bin/env python3
import argparse
from flair.cli_help import FlairHelpFormatter
from flair import FlairInputDataError
from flair.pycbio.sys import cli, fileOps
from flair.gtf_io import gtf_write_row
from flair.pycbio.hgdata.bed import BedReader, Bed
from flair.flair_bed import FlairBed


def build_parser():
    desc = "converts isoforms in bed format to a gtf, written to stdout"
    parser = argparse.ArgumentParser(prog='bed_to_gtf', formatter_class=FlairHelpFormatter, description=desc)
    parser.add_argument('inputfile', type=str, help='isoforms in bed format')
    parser.add_argument('--force', action='store_true',
                        help='convert a bed of no gene ids, one not from flair, using each isoform name as both its '
                             'transcript and gene id')
    parser.add_argument('--no_cds', action='store_true',
                        help='do not carry forward CDS from the bed file (thickstart and thickend) to the gtf')
    parser.add_argument('--is_flair_bed', action='store_true',
                        help='the input is a bed12+ file generated by flair; its extra columns are '
                             'processed and put as attributes in the gtf')
    return parser

def main():
    args = build_parser().parse_args()
    with cli.ErrorHandler():
        bed_to_gtf(query=args.inputfile, force=args.force, outputfile='/dev/stdout',
                   use_cds=not args.no_cds, is_flair_bed=args.is_flair_bed)

def _add_record(records, record):
    """Record a feature, dropping an empty range.  A CDS or UTR piece is empty when the
    thick boundary sits exactly on an exon edge, and gtf_write_row writes start + 1, so
    an empty feature came out as start > end, which is not a GTF record and which
    flair's own parser rejects on re-read."""
    if record[2] < record[3]:
        records.append(record)


def _write_gene_records(outfile, gene_id, records):
    """The gene line and its features, one gene line per chrom and strand the gene id
    appears on.  A fusion gene has blocks on two chroms, and taking the first chrom
    with the min and max over all of them gave one line spanning both."""
    by_place = {}
    for record in records:
        by_place.setdefault((record[1], record[4]), []).append(record)
    for (chrom, strand), place_records in by_place.items():
        gtf_write_row(outfile, chrom, 'FLAIR', 'gene',
                      min(r[2] for r in place_records), max(r[3] for r in place_records),
                      None, strand, None, gene_id=gene_id)
        for feature, rec_chrom, start, end, rec_strand, attrs in place_records:
            gtf_write_row(outfile, rec_chrom, 'FLAIR', feature, start, end, None, rec_strand, None,
                          attrs=attrs)


def _make_attrs(gene_id, transcript_id, bed, is_flair_bed, exon_number=None):
    """Build attrs dict for GTF output."""
    attrs = {'gene_id': gene_id, 'transcript_id': transcript_id}
    if exon_number is not None:
        attrs['exon_number'] = str(exon_number)
    if is_flair_bed:
        for name, val in bed.get_named_extra_attrs():
            attrs[name] = val
    return attrs

def bed_to_gtf(query, outputfile, force=False, use_cds=True, is_flair_bed=False):
    "convert a BED to a GTF, gzipping it when the output name ends in .gz"
    gene_to_records = _collect_gene_records(query, force, use_cds, is_flair_bed)
    with fileOps.opengz(outputfile, 'w') as outfile:
        for gene_id, records in gene_to_records.items():
            _write_gene_records(outfile, gene_id, records)

def _collect_gene_records(query, force, use_cds, is_flair_bed):  # noqa: C901 - FIXME: reduce complexity
    gene_to_records = {}
    my_bed_class = FlairBed if is_flair_bed else Bed
    for bed in BedReader(query, bedClass=my_bed_class):
        name = bed.name
        if ';' in name:
            name = name.replace(';', ':')

        if is_flair_bed:
            transcript_id = name
            gene_id = bed.gene_id
            if gene_id is None:
                raise FlairInputDataError(f'{query}: isoform {name} has no gene id in column 13; every row of a '
                                          'flair BED must name its gene, or use --force to take each isoform '
                                          'name as its gene id')
        elif force:
            transcript_id, gene_id = name, name
        else:
            raise FlairInputDataError(f'{query} has no gene ids: give --is_flair_bed for a bed from flair, whose gene '
                                      'ids are in column 13, or --force to use each isoform name as its gene id too')

        if gene_id not in gene_to_records:
            gene_to_records[gene_id] = []

        attrs = _make_attrs(gene_id, transcript_id, bed, is_flair_bed)
        _add_record(gene_to_records[gene_id], ('transcript', bed.chrom, bed.chromStart, bed.chromEnd, bed.strand, attrs))

        for b, blk in enumerate(bed.blocks):
            # 1-based and counted 5' to 3', as the GTF specification has it
            number = b + 1 if bed.strand == '+' else len(bed.blocks) - b
            exon_attrs = _make_attrs(gene_id, transcript_id, bed, is_flair_bed, exon_number=number)
            _add_record(gene_to_records[gene_id], ('exon', bed.chrom, blk.start, blk.end, bed.strand, exon_attrs))
            if use_cds and _has_cds(bed):
                _add_cds_records(gene_to_records[gene_id], bed, blk, attrs, exon_attrs)

    return gene_to_records


def _has_cds(bed):
    """A BED names a CDS with thickStart below thickEnd.  A thick range covering the
    whole transcript is taken for an absent CDS, as gtf_to_bed wrote one before it
    used the thickStart == thickEnd convention."""
    return (bed.thickStart != bed.thickEnd) and ((bed.thickStart != bed.chromStart) or (bed.thickEnd != bed.chromEnd))


def _utr_feature(strand, before_cds):
    "the name of the UTR part of an exon before or after the CDS on this strand"
    if before_cds:
        return '5UTR' if strand == '+' else '3UTR'
    else:
        return '3UTR' if strand == '+' else '5UTR'


def _add_cds_records(records, bed, blk, attrs, exon_attrs):
    """The CDS and UTR parts of one block, each written only where it is not empty, so
    a block holding the whole CDS gets a UTR on both sides of it."""
    utr_left_end = min(blk.end, bed.thickStart)
    if blk.start < utr_left_end:
        _add_record(records, (_utr_feature(bed.strand, True), bed.chrom, blk.start, utr_left_end,
                              bed.strand, exon_attrs))
    cds_start, cds_end = max(blk.start, bed.thickStart), min(blk.end, bed.thickEnd)
    if cds_start < cds_end:
        _add_record(records, ('CDS', bed.chrom, cds_start, cds_end, bed.strand, exon_attrs))
        _add_start_codon(records, bed, blk, attrs)
    utr_right_start = max(blk.start, bed.thickEnd)
    if utr_right_start < blk.end:
        _add_record(records, (_utr_feature(bed.strand, False), bed.chrom, utr_right_start, blk.end,
                              bed.strand, exon_attrs))


def _add_start_codon(records, bed, blk, attrs):
    "the start codon, where this block holds the first base of the CDS"
    if (bed.strand == '+') and (blk.start <= bed.thickStart < blk.end):
        _add_record(records, ('start_codon', bed.chrom, bed.thickStart,
                              min(bed.thickStart + 3, blk.end), bed.strand, attrs))
    elif (bed.strand == '-') and (blk.start < bed.thickEnd <= blk.end):
        _add_record(records, ('start_codon', bed.chrom, max(bed.thickEnd - 3, blk.start),
                              bed.thickEnd, bed.strand, attrs))


if __name__ == "__main__":
    main()
